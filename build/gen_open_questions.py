#!/usr/bin/env python3
"""Generate docs/open-questions.md — the index — from docs/open-questions/.

The register is a DIRECTORY now, one file per question, because that is the only
shape in which two parallel sessions cannot both issue id 99 and have git merge
them into one file without a word. See docs/open-questions/README.md and
build/check_ids.py for why, and what it cost four times.

This file is the index, not the register. It exists so a reader still has one
place to look and one place to link from, and so the 1,522 `OQ <n>` references
across the corpus still land somewhere. Editing it does nothing: the next run
overwrites it. Edit the question's own file.

`--check` re-generates in memory and exits 1 if the committed index has drifted,
which is the same guarantee `tests/test_wp46_packs.py` gives dist/taxonomy.json —
seventeen tests read that artefact as though it were source, and it went stale.
"""
import os, sys, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QDIR = os.path.join(ROOT, "docs", "open-questions")
INDEX = os.path.join(ROOT, "docs", "open-questions.md")



def _check_ids():
    """check_ids, through modcache -- never a local by-path loader (see CLAUDE.md). The
    reader, the status vocabulary and the filename rule live in ONE place: a second copy
    here is exactly how the citation grammar came to be spelled three ways."""
    sys.path.insert(0, os.path.join(ROOT, "build"))
    import modcache
    return modcache.load("check_ids", os.path.join(ROOT, "build", "check_ids.py"))


def render():
    _ci = _check_ids()
    qs, errors = _ci.read_questions()
    if errors:
        raise SystemExit("refusing to generate an index over a register that does not "
                         "check out:\n  " + "\n  ".join(errors))

    def title_of(rec):
        text = open(os.path.join(QDIR, rec["file"]), encoding="utf-8").read()
        m = re.search(r"^# OQ \d+ — (.+)$", text, re.M)
        return m.group(1).strip() if m else rec["file"]

    open_ids = sorted(k for k, v in qs.items() if v["state"] == "open")
    settled = sorted(k for k, v in qs.items() if v["state"] == "settled")

    L = ["# Open questions", "",
         "*Generated by `build/gen_open_questions.py` from `docs/open-questions/`, one file",
         "per question. **Edit the question's own file, never this index** — the next run",
         "overwrites it. The register's own history, including the four id-collision",
         "conversion tables, is in [`docs/open-questions/README.md`](open-questions/README.md).*",
         "",
         "Decisions deferred rather than made quietly. Two of these came from authoring the",
         "Georgian kit end to end, which was the point of doing it.",
         "",
         f"**{len(qs)} questions, of which {len(open_ids)} are open.** A question is OPEN while",
         "it awaits a ruling; the two HALF CLOSED entries count as open, because a half-closed",
         "question is an open one. Status words in use, and no others —",
         "**open:** " + ", ".join(f"`{w}`" for w in _ci.OPEN) + ";",
         "**settled:** " + ", ".join(f"`{w}`" for w in _ci.SETTLED) + ".",
         "`build/check_ids.py` fails the build on any other word rather than assuming it benign.",
         ""]

    for heading, ids, blurb in (
        ("Open", open_ids, "Awaiting a ruling. This is the list to read first."),
        ("Settled", settled, "Ruled, closed or recorded as a standing disclosure. Kept in full: "
                             "the ruling and the original question both, because what was asked "
                             "stays legible beside what was decided.")):
        L += [f"## {heading} — {len(ids)}", "", blurb, "",
              "| | status | question |", "|---|---|---|"]
        for i in ids:
            r = qs[i]
            L.append(f"| **{i}** | {r['status']} | "
                     f"[{title_of(r)}](open-questions/{r['file']}) |")
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        have = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if have != text:
            print("docs/open-questions.md is STALE — run `python3 build/gen_open_questions.py`")
            return 1
        print("docs/open-questions.md is current.")
        return 0
    open(INDEX, "w", encoding="utf-8").write(text)
    print(f"wrote {INDEX} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
