    if bad:
        return bad
    PE = SURF._mod("proportion_engine")
    out = []
    for pid, P in sorted(run["plate"].items()):
        if P is None:
            continue
        pack = PE.resolve(pid)
        record = set()
        for aid, a in (pack.get("assemblies") or {}).items():
            for m in a.get("members", []):
                if "projection_parts" not in m:
                    record.add("%s.%s" % (aid, m["id"]))
