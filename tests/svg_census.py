@check("B1", "bench-sheet", "every window, exterior door and door onto an at-grade appendage the bench "
       "draws is cut in its OWN wall: outside its room's own face, as deep as the wall the record states",
       "every exterior opening, and every interior door standing in an exterior wall (a door onto an "
       "at-grade appendage), on every placed level of every plan, as the bench computes it")
def b1():
    run = _bench_run()
    if isinstance(run, str):
        return [row("B1", "bench-sheet", "cne", run)]
    RP, AS = SURF._mod("render_plan"), SURF._mod("assemblies")
    out = []
    for pid, rec in sorted(_sheets().items()):
        placed = rec["placed"]
        t = AS.wall_thickness(placed)["exterior_in"] / 12.0
        # WP-14.6's second audit: THE POPULATION WAS THE EXTERIOR ENTRIES, AND A DOOR ONTO A TERRACE
        # IS AN INTERIOR ONE. The terrace is a room, placed OUTSIDE the block against the room's own
        # face (build/appendages.py), so the door between them is an interior entry standing in the
        # house's exterior wall -- PL2 already counts it so (WP-14.4 §III). The bench was served no
        # appendages and named both such doors on the shipped plans undrawable, and this row agreed,
        # because neither was in its population.
        aps = {}
        for a in ((placed.get("appendages") or {}).get("placed") or []):
            aps.setdefault(a.get("level", 0), set()).add(a["room"])
        bad, n = [], 0
        for i, lv in enumerate(lv for lv in placed.get("levels", []) if any(r.get("geometry") for r in lv["rooms"])):
            got = run["marks"].get("%s@%s" % (pid, lv.get("index", i)))
            if got is None:
                continue
            op = RP.openings_of_level(placed, lv, i)
            want = [("win", d) for d in op["windows"]] + [("door", d) for d in op["exterior"]]
            marks = [("win", m) for m in got["windows"]] + [("door", m) for m in got["exterior"]]
            for kind, d in want:
                n += 1
                e = d["edge_ft"]
                lo, hi = (e - t, e) if d["wall"] in "SW" else (e, e + t)
                m = next((m for k, m in marks if k == kind and m["room"] == d.get("room") and m["wall"] == d["wall"]
                          and abs(m["along"] - d["at_ft"]) < 1e-3), None)
                if m is None:
                    bad.append("L%s %s %s %s at %.2f is not drawn" % (lv.get("index", i), kind, d.get("room"), d["wall"], d["at_ft"]))
                elif abs(m["across"][0] - lo) > 1e-3 or abs(m["across"][1] - hi) > 1e-3:
                    bad.append("L%s %s %s %s drawn across %.2f..%.2f where its wall is %.2f..%.2f"
                               % (lv.get("index", i), kind, d.get("room"), d["wall"], m["across"][0], m["across"][1], lo, hi))
            geo = {r["id"]: r["geometry"] for r in lv["rooms"] if r.get("geometry")}
            here = aps.get(lv.get("index", i), set())
            for d in op["interior"]:
                room = [x for x in d["pair"] if x in geo]
                if not room or not any(x in here for x in d["pair"]):
                    continue
                n += 1
                g, e = geo[room[0]], d["at_ft"]
                # the room's face the door stands on: the nearer of the two across the line
                if d["horiz"]:
                    wl = "S" if abs(e - g["y_ft"]) <= abs(e - (g["y_ft"] + g["depth_ft"])) else "N"
                else:
                    wl = "W" if abs(e - g["x_ft"]) <= abs(e - (g["x_ft"] + g["width_ft"])) else "E"
                lo, hi = (e - t, e) if wl in "SW" else (e, e + t)
                who = "L%s door %s %s" % (lv.get("index", i), "-".join(d["pair"]), wl)
                m = next((m for m in got.get("interior") or [] if sorted(m["pair"]) == sorted(d["pair"])
                          and abs(m["along"] - d["pos_ft"]) < 1e-3), None)
                if m is None:
                    bad.append("%s at %.2f is not drawn" % (who, d["pos_ft"]))
                elif abs(m["across"][0] - lo) > 1e-3 or abs(m["across"][1] - hi) > 1e-3:
                    bad.append("%s drawn across %.2f..%.2f where its wall is %.2f..%.2f"
                               % (who, m["across"][0], m["across"][1], lo, hi))
        if not n:
            out.append(row("B1", pid, "cne", "no exterior opening is placed on this record"))
        elif bad:
            out.append(row("B1", pid, "disagrees", "%d of %d: %s" % (len(bad), n, "; ".join(bad[:3]))))
        else:
            out.append(row("B1", pid, "agrees", "%d openings" % n))
    return out


@check("B2", "bench-sheet", "the bench is served the plate's own wall bodies for every placed level -- "
       "the envelope of every element, the joins, the bearing lines, the partitions and their holes",
       "every placed level of every plan")
def b2():
    run = _bench_run()
    if isinstance(run, str):
        return [row("B2", "bench-sheet", "cne", run)]
    RP = SURF._mod("render_plan")
    out = []
    for pid, rec in sorted(_sheets().items()):
        served = run["served"][pid].get("walls")
        plate = RP.wall_bodies(rec["placed"])
        if not served:
            out.append(row("B2", pid, "disagrees", "the placement serves no wall bodies, so the bench "
                           "draws its own ring round the footprint"))
            continue
        # the served bands are rounded to 1e-4 ft for the wire; hold them to the plate's within that
        key = lambda b: (b["wall"], round(b["x_ft"], 2), round(b["y_ft"], 2))  # noqa: E731
        # THE INK IS CHOSEN BY `kind` AND THE BODY IS AS THICK AS `t_ft` (WP-14.6, auditor C). This
        # compared the walls and the four dimensions only, and the bench picks masonry or partition
        # poche by `kind`: a server dropping it drew all 88 Tidewater bands as partitions, the
        # plate's 61 masonry bands among them, and this row agreed.
        dims = ("x_ft", "y_ft", "width_ft", "depth_ft", "t_ft")
        diff = []
        for s_, p_ in zip(served, plate):
            a, b = sorted(s_["bands"], key=key), sorted(p_["bands"], key=key)
            same = len(a) == len(b) and s_["level"] == p_["level"] and all(
                x["wall"] == y["wall"] and x.get("kind") == y.get("kind")
                and all(abs((x.get(k) or 0.0) - (y.get(k) or 0.0)) <= 1e-4 for k in dims)
                for x, y in zip(a, b))
            if not same:
                kinds = sum(1 for x, y in zip(a, b) if x.get("kind") != y.get("kind"))
                diff.append("level %s: %d served against %d on the plate%s" % (
                    p_["level"], len(a), len(b),
                    (", %d of another kind" % kinds) if kinds else ""))
        if len(served) != len(plate):
            diff.append("%d levels served against %d on the plate" % (len(served), len(plate)))
        out.append(row("B2", pid, "disagrees" if diff else "agrees",
                       "; ".join(diff) if diff else "%d bodies" % sum(len(p_["bands"]) for p_ in plate)))
    return out


