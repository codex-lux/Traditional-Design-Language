# WHAT COUNTS AS EMITTING SVG. The first version matched `<svg` alone and was blind to a React
# component that returns a `<path>` or a `<line>` inside its parent's `<svg>` -- it never writes
# the root element, and it is exactly where a second spelling of a mark would grow. So a primitive
# counts too, but only followed by an ATTRIBUTE: `<path>[]` in a docstring and `(?P<path>` in a
# route regex are prose and code, not ink. A carrier that injects a server's SVG is found by
# `dangerouslySetInnerHTML`, because it writes no primitive of its own.
_EMIT = re.compile(r"<(svg|path|polyline|polygon|circle|ellipse|line|rect)\s+[a-zA-Z]|"
                   r"createElementNS|image/svg\+xml|dangerouslySetInnerHTML")
_SKIP = re.compile(r"^(tests/|docs/|dist/|assets/|workbench/app/e2e/|workbench/server/tests/|"
                   r"workbench/app/dist/)|node_modules|\.(md|json|svg|txt|b64)$|\.test\.m?js$")


def emitters(root=ROOT):
    """Every tracked or new file (never a walk: WP-13.2's rule) that mentions an SVG emitter."""
    files = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=root,
                           capture_output=True, text=True, check=True).stdout.split()
    out = []
    for f in sorted(files):
        if _SKIP.search(f):
            continue
        try:
            with open(os.path.join(root, f), encoding="utf-8", errors="ignore") as fh:
                if _EMIT.search(fh.read()):
                    out.append(f)
        except (IsADirectoryError, FileNotFoundError):
            continue
    return out


def unregistered(root=ROOT):
    named = {r["file"] for r in REGISTRY}
    return [f for f in emitters(root) if f not in named]


# ------------------------------------------------------------------ the checks
CHECKS = {}


def check(cid, surface, statement, population):
    def wrap(fn):
        CHECKS[cid] = {"id": cid, "surface": surface, "statement": statement,
                       "population": population, "fn": fn}
        return fn
    return wrap


def row(cid, subject, verdict, detail=""):
    assert verdict in ("agrees", "disagrees", "cne"), verdict
    return {"check": cid, "subject": subject, "verdict": verdict, "detail": detail}


_PLATES = None


def _profile_assets():
    """The committed plates, read back from the files a reader is served."""
    global _PLATES
    if _PLATES is None:
        doc = json.load(open(os.path.join(ROOT, "assets", "manifest.json")))
        _PLATES = []
        for a in doc["assets"]:
            g = a.get("generated_from")
            if not g:
                continue
            path = os.path.join(ROOT, a["file"]["path"])
            svg = open(path).read()
            _PLATES.append((a, g, SURF.ProfilePlate(svg),
                            SURF.profile_record(g["pack"], (g.get("parameters") or {}).get("assembly"),
                                                g.get("module_in") or 6.0)))
    return _PLATES


def _unreadable(pl):
    """Why this plate's geometry cannot be read back, or None. A plate that states no frame, or
    whose silhouette is not one filled path, is COULD NOT EVALUATE with that reason -- never a
    crash, which would stop every later check, and never a pass."""
    if pl.plate is None:
        return "the plate states no data-frame, so its pixels cannot be read as inches"
    if pl.outline is None:
        return "%d filled paths where one silhouette was expected" % pl.n_outlines
    return None


def _fig(pattern, text):
    m = re.search(pattern, text)
    return float(m.group(1)) if m else None


@check("P1", "profile-plates", "the column diameter a plate prints is the diameter it is drawn at",
       "every committed profile plate")
def p1():
    out = []
    for a, g, pl, rec in _profile_assets():
        got = _fig(r"at a ([\d.]+)″ column", pl.flat_text)
        want = rec["lower_diameter_in"]
        if got is None:
            out.append(row("P1", a["id"], "cne", "no column diameter printed"))
        elif abs(got - want) > 0.5:
            out.append(row("P1", a["id"], "disagrees", "prints %g in, drawn at %g in" % (got, want)))
        else:
            out.append(row("P1", a["id"], "agrees"))
    return out


@check("P2", "profile-plates", "the relief a plate prints is the relief its ink draws",
       "every committed profile plate")
def p2():
    out = []
    for a, g, pl, rec in _profile_assets():
        got = _fig(r"([\d.]+)″ of relief", pl.flat_text)
        # A plate whose ink draws no relief SAYS so in words rather than printing a figure
        # (WP-14.2), and "no relief" is a claim of zero that the ink can contradict -- read it as
        # one, never as a plate that printed nothing.
        if got is None and re.search(r"\bno relief\b", pl.flat_text):
            got = 0.0
        why = _unreadable(pl) or (None if got is not None else "no relief printed")
        if why:
            out.append(row("P2", a["id"], "cne", why))
            continue
        drawn = max(u for u, v in pl.points()) - pl.naked()
        if abs(got - drawn) > 0.011:
            out.append(row("P2", a["id"], "disagrees", "prints %.2f in, draws %.2f in" % (got, drawn)))
        else:
            out.append(row("P2", a["id"], "agrees"))
    return out


