def _gaps(lo, hi, covers):
    """The intervals of [lo, hi] no cover reaches: the glass between the members."""
    out, at = [], lo
    for a, b in sorted(covers):
        if a > at + 1e-6:
            out.append((at, a))
        at = max(at, b)
    if hi > at + 1e-6:
        out.append((at, hi))
    return out


