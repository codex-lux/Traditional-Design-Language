@check("P4", "profile-plates", "every mark of ink is inside the plate's viewBox",
       "every committed profile plate")
def p4():
    out = []
    for a, g, pl, rec in _profile_assets():
        x0, y0, w, h = pl.ink.viewbox()
        bad = 0
        for it in pl.ink.items:
            if it.tag == "text" or not it.cmds:
                continue
            for x, y in it.points(n=24):
                if x < x0 - 0.5 or y < y0 - 0.5 or x > x0 + w + 0.5 or y > y0 + h + 0.5:
                    bad += 1
        out.append(row("P4", a["id"], "disagrees" if bad else "agrees",
                       ("%d sampled point(s) outside the viewBox" % bad) if bad else ""))
    return out


@check("P5", "profile-plates", "every member boundary the record states is a drawn vertex, and "
       "the drawn height is the stated height", "every committed profile plate")
def p5():
    out = []
    for a, g, pl, rec in _profile_assets():
        if _unreadable(pl):
            out.append(row("P5", a["id"], "cne", _unreadable(pl)))
            continue
        vs = sorted({round(p[1][1], 4) for p in pl.segments_in_model()} |
                    {round(p[2][1], 4) for p in pl.segments_in_model()})
        missing = []
        for m in rec["members"]:
            if rec["side_by_side"]:
                continue
            for b in (m["y_bottom_in"], m["y_top_in"]):
                if not any(abs(b - v) <= 0.01 for v in vs):
                    missing.append("%s@%.3f" % (m["id"], b))
        pts = pl.points()
        span = max(v for u, v in pts) - min(v for u, v in pts)
        want = max(m["y_top_in"] for m in rec["members"]) - min(m["y_bottom_in"] for m in rec["members"])
        if missing or abs(span - want) > 0.01:
            out.append(row("P5", a["id"], "disagrees",
                           "drawn %.3f in against %.3f; boundaries not drawn: %s"
                           % (span, want, ", ".join(sorted(set(missing))[:6]) or "none")))
        else:
            out.append(row("P5", a["id"], "agrees"))
    return out


@check("P6", "profile-plates", "a member whose face is at its mid-height (a step or a half round) "
       "is drawn out to the face its record states", "members with a published projection")
def p6():
    out = []
    PROF = SURF._mod("profiles")
    for a, g, pl, rec in _profile_assets():
        if _unreadable(pl):
            out.append(row("P6", a["id"], "cne", _unreadable(pl)))
            continue
        naked = pl.naked()
        datum = pl.plate.get("datum")
        bad = []
        judged = 0
        for m in rec["members"]:
            if rec["side_by_side"] or not rec["published"].get(m["id"]):
                continue
            if (m.get("profile") or "flat") not in SURF.FACE_AT_MID:
                continue
            want = PROF.outer_face(naked, m.get("projection_in") or 0.0, datum == "axis")
            got = pl.extent_at((m["y_bottom_in"] + m["y_top_in"]) / 2.0)
            judged += 1
            if got is None or abs(got - want) > 0.02:
                bad.append("%s drawn to %s, record %.3f" % (m["id"], "nothing" if got is None else "%.3f" % got, want))
        if not judged:
            out.append(row("P6", a["id"], "cne", "no member of a kind this check reads"))
        elif bad:
            out.append(row("P6", a["id"], "disagrees", "; ".join(bad[:4])))
        else:
            out.append(row("P6", a["id"], "agrees", "%d member(s)" % judged))
    return out


@check("P7", "profile-plates", "a member the record gives no projection for is SAID to have "
       "none, not drawn as though measured flush -- and a plate where every member publishes one "
       "says that", "every committed profile plate")
def p7():
    out = []
    for a, g, pl, rec in _profile_assets():
        n = sum(1 for m in rec["members"] if not rec["published"].get(m["id"]))
        if not n:
            # THE COUNT GOES ON EVERY PLATE (decision 2, WP-14.2): silence on a complete plate
            # reads exactly like silence on a plate nobody checked.
            said = re.search(r"ALL (\d+) MEMBER\(S\) PUBLISH A PROJECTION", pl.flat_text.upper())
            if said and int(said.group(1)) == len(rec["members"]):
                out.append(row("P7", a["id"], "agrees", "all %d published, said" % len(rec["members"])))
            else:
                out.append(row("P7", a["id"], "disagrees",
                               "every member publishes a projection and the plate %s"
                               % ("says %s" % said.group(1) if said else "does not say so")))
            continue
        said = re.search(r"(\d+) MEMBER\(S\)[^.]*NO PROJECTION PUBLISHED", pl.flat_text.upper())
        if said and int(said.group(1)) == n:
            out.append(row("P7", a["id"], "agrees", "%d unpublished, said" % n))
        else:
            out.append(row("P7", a["id"], "disagrees",
                           "%d member(s) carry no projection in the record; the plate %s"
                           % (n, "says %s" % said.group(1) if said else "says nothing")))
    return out


