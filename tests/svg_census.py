@check("P10", "profile-plates", "a member whose record confidence is not high is marked as such "
       "on the plate -- in its own label, and by a dashed outline over its own height",
       "plates holding a medium- or low-confidence member")
def p10():
    out = []
    for a, g, pl, rec in _profile_assets():
        # an UNSTATED confidence is not a high one; every member states one today (733 of 733)
        weak = [m for m in rec["members"]
                if (rec["raw"].get(m["id"], {}).get("confidence") or "unstated") != "high"]
        if not weak:
            continue
        # an unstated confidence is marked as one (WP-14.2), so its word counts as a mark. The
        # mark is the LABEL's ", <level> confidence" -- counting the bare phrase let the plate's
        # own footer sentence, which explains the dashes, satisfy this check by itself.
        marked = len(re.findall(r", (?:LOW|MEDIUM|UNSTATED) CONFIDENCE\b", pl.flat_text.upper()))
        # THE INK AS WELL AS THE WORDS (WP-14.2): one dashed outline per weak member with height,
        # read back through the frame and held to that member's own span up the stack.
        outlined = set()
        if pl.plate is not None:
            for it in pl.ink.select("path"):
                if "confidence" not in it.classes:
                    continue
                vs = [pl.model(p)[1] for p in it.points(n=4, lines=True)]
                for m in weak:
                    if abs(min(vs) - m["y_bottom_in"]) < 0.01 and abs(max(vs) - m["y_top_in"]) < 0.01:
                        outlined.add(m["id"])
        tall = [m for m in weak if m["y_top_in"] - m["y_bottom_in"] > 1e-6]
        unmarked = sorted(m["id"] for m in tall if m["id"] not in outlined)
        # every weak member carries its mark in its own label, so the count must match
        if marked >= len(weak) and not unmarked:
            out.append(row("P10", a["id"], "agrees", "%d marked" % len(weak)))
        else:
            out.append(row("P10", a["id"], "disagrees",
                           "%d of %d member(s) are medium or low confidence; %d marked in words; "
                           "no dashed outline over %s" % (len(weak), len(rec["members"]), marked,
                                                           unmarked[:4] or "none missing")))
    return out


# A MEMBER'S OWN NAME CAN MAKE IT A CURVE (WP-14.6, audit F7): "Ovolo of the abacus" is an ovolo
# whatever its `profile` says, and three members so named were drawn SQUARE -- Vignola's
# Corinthian one with "Quarter-round 2 parts high" in its own note. The member is the name's
# HEAD noun, after any position word ("Upper torus"), or the noun after the comma in Gibbs's
# "Abacus, ovolo" form; a name that only MENTIONS a curve ("Fillet under the scotia", "Fillet of
# the cymatium") names a neighbour and is not read as one.
_CURVE_WORD = r"(ovolo|cyma|cymatium|torus|scotia|cavetto|astragal|bead|echinus|quarter-round|ogee)"
_CURVE_NAME = re.compile(r"^(?:(?:first|second|third|lower|upper|great|small|large|the)\s+)*"
                         + _CURVE_WORD + r"\b|,\s*" + _CURVE_WORD + r"\s*$", re.I)

# WHAT A CHECK JUDGED, MEMBER BY MEMBER (WP-14.6's second audit, M11). P11's population is two
# readers ORed together -- the member's profile kind and its own name -- and blinding the name
# reader outright (`_CURVE_NAME` matching nothing) left every P11 row agreeing and the census
# unmoved: a plate with fewer members to judge has fewer to find drawn straight, and an agreement
# over fewer members is still an agreement (N2's lesson, `tests/test_plate_review.N2_FIGURES`).
# The check records here what it judged; `tests/test_svg_census.py` holds that to both readers.
POPULATION = {}


@check("P11", "profile-plates", "a curved member drawn as a straight line says so -- curved by its "
       "profile kind or by its own name", "plates holding a curved member")
def p11():
    out = []
    judged = POPULATION["P11"] = []
    for a, g, pl, rec in _profile_assets():
        # A member whose projection is unpublished is not drawn straight: it is not constructed
        # at all, and P7 holds the plate to saying so (WP-14.2).
        curved = [m for m in rec["members"]
                  if ((m.get("profile") or "") in SURF.CURVED or _CURVE_NAME.search(m.get("name") or ""))
                  and not rec["side_by_side"] and rec["published"].get(m["id"])]
        judged.extend((a["id"], m["id"]) for m in curved)
        if not curved:
            continue
        if _unreadable(pl):
            out.append(row("P11", a["id"], "cne", _unreadable(pl)))
            continue
        straight = [m["id"] for m in curved
                    if not pl.segments_within(m["y_bottom_in"], m["y_top_in"])]
        if not straight:
            out.append(row("P11", a["id"], "agrees"))
            continue
        said = re.search(r"(\d+) CURVED MEMBER\(S\) DRAWN STRAIGHT", pl.flat_text.upper())
        if said and int(said.group(1)) == len(straight):
            out.append(row("P11", a["id"], "agrees", "%d straight, said" % len(straight)))
        else:
            out.append(row("P11", a["id"], "disagrees",
                           "%s drawn straight and not said" % ", ".join(straight[:5])))
    return out


