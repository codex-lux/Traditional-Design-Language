# ------------------------------------------------------------------ running it
def run(only=None):
    rows = []
    for cid, c in CHECKS.items():
        if only and c["surface"] not in only and cid not in only:
            continue
        rows.extend(c["fn"]())
    return rows


def summary(rows):
    out = {}
    for cid, c in CHECKS.items():
        rs = [r for r in rows if r["check"] == cid]
        if not rs and cid not in {r["check"] for r in rows}:
            pass
        out[cid] = {"surface": c["surface"], "statement": c["statement"], "population": c["population"],
                    "rows": len(rs), "agrees": sum(r["verdict"] == "agrees" for r in rs),
                    "disagrees": sum(r["verdict"] == "disagrees" for r in rs),
                    "cne": sum(r["verdict"] == "cne" for r in rs)}
    return out


def disagreement_ids(rows):
    return sorted("%s:%s" % (r["check"], r["subject"]) for r in rows if r["verdict"] == "disagrees")


def disagreements(rows):
    """{id: detail} for every row that disagrees. THE DETAIL IS PINNED WITH THE ID, and the reason
    is measured: with ids alone, corrupting V1's own rung table and making V5 count the wrong
    muntins both left the build green -- every V1 and V5 row already disagreed, so a change in
    WHAT a row reports was invisible. A row red for one cause cannot report a second unless its
    figures are held as well as its verdict."""
    return {"%s:%s" % (r["check"], r["subject"]): r["detail"] for r in rows if r["verdict"] == "disagrees"}


def render_doc_tables(rows):
    s = summary(rows)
    lines = ["| check | surface | statement | population | rows | agrees | disagrees | could not evaluate |",
             "|---|---|---|---|---:|---:|---:|---:|"]
    for cid, x in s.items():
        lines.append("| %s | %s | %s | %s | %d | %d | %d | %d |" % (
            cid, x["surface"], x["statement"], x["population"], x["rows"], x["agrees"],
            x["disagrees"], x["cne"]))
    reg = ["| id | role | file | surface / reason |", "|---|---|---|---|"]
    for r in REGISTRY:
        reg.append("| %s | %s | `%s` | %s |" % (r["id"], r["role"], r["file"],
                                                r.get("surface") or r.get("reason")))
    return "\n".join(reg), "\n".join(lines)


_MARK = ("<!-- census:%s:begin -->", "<!-- census:%s:end -->")


def splice(text, name, body):
    b, e = _MARK[0] % name, _MARK[1] % name
    i, j = text.index(b) + len(b), text.index(e)
    return text[:i] + "\n" + body + "\n" + text[j:]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--write-doc", action="store_true")
    ap.add_argument("--surface", action="append")
    ap.add_argument("--diff", action="store_true",
                    help="what moved against tests/fixtures/ink_known_disagreements.json")
    ap.add_argument("--pin", action="store_true",
                    help="rewrite the known disagreements to the live census (say why in the commit)")
    a = ap.parse_args()
    rows = run(set(a.surface) if a.surface else None)
    if a.diff or a.pin:
        if a.surface:
            ap.error("--diff and --pin read the WHOLE census: a partial run would call every "
                     "unrun row fixed")
        doc = json.load(open(KNOWN))
        known, live = doc["disagreements"], disagreements(rows)
        new = sorted(set(live) - set(known))
        fixed = sorted(set(known) - set(live))
        moved = sorted(k for k in set(known) & set(live) if known[k] != live[k])
        for label, ids in (("NEW", new), ("FIXED", fixed), ("MOVED", moved)):
            print("%s %d" % (label, len(ids)))
            for k in ids:
                print("   %s  %s" % (k, live.get(k, known.get(k)) if label != "MOVED"
                                     else "%r -> %r" % (known[k], live[k])))
        if a.pin:
            doc["disagreements"] = {k: live[k] for k in sorted(live)}
            with open(KNOWN, "w", encoding="utf-8") as fh:
                json.dump(doc, fh, indent=1, ensure_ascii=False)
                fh.write("\n")
            print("pinned", len(live))
        return 0
    if a.json:
        print(json.dumps({"summary": summary(rows), "rows": rows}, indent=1))
        return 0
    if a.write_doc:
        reg, table = render_doc_tables(rows)
        text = open(DOC).read()
        text = splice(splice(text, "registry", reg), "checks", table)
        open(DOC, "w").write(text)
        print("wrote", os.path.relpath(DOC, ROOT))
        return 0
    for cid, x in summary(rows).items():
        print("%-4s %-18s agrees %4d  disagrees %4d  cne %4d   %s"
              % (cid, x["surface"], x["agrees"], x["disagrees"], x["cne"], x["statement"]))
    print("\nunregistered SVG emitters:", unregistered() or "none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
