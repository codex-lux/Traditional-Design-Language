# ------------------------------------------------------------------ the order stack (link 2)
# The orders tool and the Proportions plate draw a WHOLE column and entablature, stacked by the
# engine's `stack_for` and dimensioned by `dimension()` -- the orders page through a JavaScript
# port of both. These checks hold that stack to what each pack STATES, before any ink: a column
# drawn at the wrong height is wrong on every surface that draws it, and asking each surface
# separately would report one defect three times.
def _order_packs():
    PE = SURF._mod("proportion_engine")
    for pid in sorted(PE.PACKS):
        if (PE.PACKS[pid].get("kind") or "") != "order-system":
            continue
        pack = PE.resolve(pid)
        dim = PE.dimension(pack, module_in=6.0)
        heights = {a["id"]: a["y_top_in"] - a["y_bottom_in"] for a in dim["assemblies"]}
        yield pid, pack, dim, heights


@check("E1", "order-stack", "the column drawn (base + shaft + capital) is the column height the "
       "pack states", "order packs stating a column height")
def e1():
    out = []
    for pid, pack, dim, H in _order_packs():
        col = dim["totals"].get("column_height_in")
        if not col:
            continue
        if not all(a in H for a in ("base", "shaft", "capital")):
            out.append(row("E1", pid, "cne", "the stack holds %s, not a whole column"
                           % ", ".join(sorted(H)) or "nothing"))
            continue
        drawn = sum(H[a] for a in ("base", "shaft", "capital"))
        if abs(drawn - col) > 0.01:
            out.append(row("E1", pid, "disagrees", "states %.2f in, draws %.2f in (at a 6 in module)"
                           % (col, drawn)))
        else:
            out.append(row("E1", pid, "agrees"))
    return out


@check("E2", "order-stack", "the entablature drawn is the one the pack itself states",
       "order packs that state a whole entablature")
def e2():
    out = []
    PE = SURF._mod("proportion_engine")
    for pid, pack, dim, H in _order_packs():
        stated = dim["totals"].get("entablature_height_in")
        if not stated:
            continue
        drawn = sum(H.get(a, 0.0) for a in ("architrave", "frieze", "cornice", "entablature"))
        owner = PE.assembly_owner(pid, "entablature")
        if abs(drawn - stated) > 0.01:
            out.append(row("E2", pid, "disagrees",
                           "%s states %.2f in; the stack draws %.2f in from %s's %s"
                           % (owner, stated, drawn, PE.assembly_owner(pid, "cornice") or "nobody",
                              "architrave, frieze and cornice" if "cornice" in H else "entablature")))
        else:
            out.append(row("E2", pid, "agrees"))
    return out


@check("E3", "order-stack", "an assembly offered as an ALTERNATIVE to another is never stacked "
       "on it (Benjamin's subplinth stands a column instead of a pedestal)",
       "order packs stating a subplinth")
def e3():
    out = []
    for pid, pack, dim, H in _order_packs():
        if "subplinth" not in (pack.get("assemblies") or {}):
            continue
        stacked = [a["id"] for a in dim["assemblies"]]
        if "subplinth" in stacked and "pedestal" in stacked:
            out.append(row("E3", pid, "disagrees", "pedestal and subplinth both stacked (%.2f + %.2f in)"
                           % (H["pedestal"], H["subplinth"])))
        else:
            out.append(row("E3", pid, "agrees"))
    return out


@check("E4", "order-stack", "the pedestal die is drawn at a naked the record gives, never the "
       "1.2 x R stand-in profiles.pack_geometry takes when the base publishes no plinth",
       "order packs drawing a pedestal")
def e4():
    out = []
    for pid, pack, dim, H in _order_packs():
        asms = {a["id"]: a for a in dim["assemblies"]}
        if "pedestal" not in asms and "subplinth" not in asms:
            continue
        base = asms.get("base")
        plinth = max([m.get("projection_in") or 0.0 for m in base["members"]], default=0.0) if base else 0.0
        if plinth:
            out.append(row("E4", pid, "agrees"))
        else:
            out.append(row("E4", pid, "disagrees",
                           "the base publishes no projection, so the die is drawn at 1.2 x R, a "
                           "figure no record states"))
    return out


